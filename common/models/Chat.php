<?php

namespace common\models;

use Yii;
use yii\db\ActiveQuery;
use yii\db\ActiveRecord;
use yii\helpers\ArrayHelper;

/**
 * This is the model class for table "chat".
 *
 * @property int $id
 * @property int $status
 * @property int $created_at
 * @property int $updated_at
 * @property int $user_id
 * @property ActiveQuery|User $user
 * @property ChatGuestUser|ActiveQuery $guestUser
 * @property int $is_guest
 */
class Chat extends ActiveRecord
{
    const STATUS_CLOSED = 0;
    const STATUS_OPEN = 1;

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'chat';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['status', 'created_at', 'updated_at'], 'integer'],
            [['user_id', 'is_guest'], 'safe']
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'status' => 'Status',
            'created_at' => 'Created At',
            'updated_at' => 'Updated At',
        ];
    }

    public function save($runValidation = true, $attributeNames = null)
    {
        if ($this->isNewRecord) {
            $this->created_at = date('U');
        }
        $this->updated_at = date('U');
        return parent::save($runValidation, $attributeNames); // TODO: Change the autogenerated stub
    }

    /**
     * @return int|mixed
     */
    public static function activeChat()
    {
        $usersChats = ChatUser::find()
            ->where(['user_id' => Yii::$app->user->getId()])
            ->groupBy('chat_id')
            ->all();
        if ($usersChats) {
            $model = Chat::find()->where(['status' => Chat::STATUS_OPEN])
                ->andWhere(['in', 'id', ArrayHelper::getColumn($usersChats, 'chat_id')])
                ->one();
            if ($model) {
                return $model->id;
            }
        }
        return 0;
    }

    /**
     * @return ActiveQuery | User
     */
    public function getUser()
    {
        return $this->hasOne(User::class, ['id' => 'user_id']);
    }

    /**
     * @return ActiveQuery | ChatGuestUser
     */
    public function getGuestUser()
    {
        return $this->hasOne(ChatGuestUser::class, ['id' => 'user_id']);
    }
}
