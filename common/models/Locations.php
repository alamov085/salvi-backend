<?php

namespace common\models;

use api\job\GetCoordinate;
use Yii;
use yii\db\ActiveQuery;
use yii\db\ActiveRecord;
use yii\helpers\ArrayHelper;

/**
 * This is the model class for table "locations".
 *
 * @property int $id
 * @property int $company_id
 * @property string $name
 * @property int $zip_code
 * @property string $city
 * @property string $street
 * @property string $building
 * @property string $office
 * @property int $floor
 * @property int $phone_one
 * @property int $phone_two
 * @property string $comment
 * @property int $isActive
 * @property int $activeDate
 * @property int $budgetLocationOnly
 * @property int $created_at
 * @property CostCenter|ActiveQuery $costCenters
 * @property string $fullAddress
 * @property ActiveQuery|CompanyEntityLocation $companyEntities
 * @property int $updated_at
 * @property int $allCompanies
 * @property History|ActiveQuery $history
 * @property int $user_id_responsible
 * @property string $lat
 * @property string $lng
 * @property ActiveQuery|Order $orders
 * @property string $region
 */
class Locations extends ActiveRecord
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'locations';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['company_id', 'zip_code', 'floor', 'phone_one', 'phone_two', 'activeDate',
                'created_at', 'updated_at', 'user_id_responsible'], 'integer'],
            [['isActive', 'budgetLocationOnly', 'allCompanies'], 'boolean'],
            [['name', 'city', 'street', 'building', 'office', 'comment'], 'string', 'max' => 255],
            [['lng', 'lat', 'region'], 'safe']
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'company_id' => 'Company ID',
            'name' => 'Назва локації',
            'zip_code' => 'Поштовий індекс',
            'city' => 'Місто',
            'street' => 'Вулиця',
            'building' => 'Номер будинку',
            'office' => 'Офіс',
            'floor' => 'Поверх',
            'phone_one' => 'Робочий номер телефону',
            'phone_two' => 'Додатковий номер телефону',
            'comment' => 'Comment',
            'isActive' => 'Is Active',
            'activeDate' => 'Active Date',
            'budgetLocationOnly' => 'Budget Location Only',
            'created_at' => 'Created At',
            'updated_at' => 'Updated At',
        ];
    }

    /**
     * @return ActiveQuery | CostCenter
     */
    public function getCostCenters()
    {
        return $this->hasMany(CostCenter::class, ['location_id' => 'id']);
    }

    /**
     * @param bool $runValidation
     * @param null $attributeNames
     * @return bool
     */
    public function save($runValidation = true, $attributeNames = null)
    {
        if ($this->isNewRecord) {
            $this->created_at = date('U');
        }
        $this->updated_at = date('U');
        return parent::save($runValidation, $attributeNames); // TODO: Change the autogenerated stub
    }


    /**
     * @return ActiveQuery | CompanyEntityLocation
     */
    public function getCompanyEntities()
    {
        return $this->hasMany(CompanyEntityLocation::class, ['location_id' => 'id']);
    }

    /**
     * @param $status
     * @return bool
     */
    public function changeStatus($status)
    {
        if (in_array($status, [0, 1])) {
            $this->isActive = $status;
            return $this->save();
        }
        return false;
    }

    /**
     * @return string
     */
    public function getFullAddress()
    {
    	$result = $this->city . ', ' . $this->street . ', б.' . $this->building;
    	
    	if(!empty($this->office))
	    {
		    $result .= ', оф.' . $this->office;
	    }
	
	    if(!empty($this->floor))
	    {
		    $result .= ', поверх ' . $this->floor;
	    }
	    
        return $result;
    }

    public function afterSave($insert, $changedAttributes)
    {
        if ($insert) {
            History::saveHistory(History::LOCATION, $this->id);
        }
        parent::afterSave($insert, $changedAttributes);
    }

    /**
     * @return ActiveQuery | History
     */
    public function getHistory()
    {
        return $this->hasOne(History::class, ['entity_id' => 'id'])
            ->andOnCondition(['entity' => History::LOCATION]);
    }

    public function updateCoordination()
    {
        return Yii::$app->queue->push(new GetCoordinate(['location' => $this]));
    }

    /**
     * @return ActiveQuery | Order
     */
    public function getOrders()
    {
        return $this->hasMany(Order::class, ['location_id' => 'id']);
    }

    public static function getListOfLocationsByContract($contract_id)
    {
        /** @var  $user User */
        $user = Yii::$app->user->getIdentity();
        return self::getListOfLocationsByContractBase($contract_id, $user->company_id);
    }

    public static function getListOfLocationsByContractBase($contract_id, $company_id)
    {
        $contractLocation = Contract::find()
            ->joinWith(['locations'])
            ->where(['contract.id' => $contract_id])
            ->one();
        $contractLocationIds = [];
        if ($contractLocation) {
            $contractLocationIds = $contractLocation->listOfLocations;
        }
        return Locations::find()
            ->where(['company_id' => $company_id])
            ->andWhere(['in', 'id', $contractLocationIds])
            ->all();
    }
}
