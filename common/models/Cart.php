<?php

namespace common\models;

use api\helpers\NumberHelper;
use Yii;
use yii\db\ActiveQuery;
use yii\db\ActiveRecord;

/**
 * This is the model class for table "cart".
 *
 * @property int $id
 * @property int $order_id
 * @property int $company_id
 * @property int $user_id
 * @property int $created_at
 * @property ActiveQuery|Order $order
 * @property int $updated_at
 * @property int $total
 */
class Cart extends ActiveRecord
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'cart';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['order_id', 'user_id', 'created_at', 'updated_at', 'company_id'], 'integer'],
            ['total', 'number']
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id'         => 'ID',
            'order_id'   => 'Order ID',
            'user_id'    => 'User ID',
            'created_at' => 'Created At',
            'updated_at' => 'Updated At',
            'company_id' => 'Company ID'
        ];
    }

    public function save($runValidation = true, $attributeNames = null)
    {
        if ($this->isNewRecord) {
            $this->created_at = date('U');
        }
        $this->updated_at = date('U');
        return parent::save($runValidation, $attributeNames); // TODO: Change the autogenerated stub
    }

    /**
     * @return ActiveQuery | Order
     */
    public function getOrder()
    {
        return $this->hasOne(Order::class, ['id' => 'order_id']);
    }

    public function recalculateTotal()
    {
        $total = CartProduct::find()
            ->where(['cart_id' => $this->id])
            ->andWhere(['is_delete' => 0])
            ->sum('total_sum');
        $this->total = ($total) ? NumberHelper::convert($total) : 0;
        return ($this->save()) ? NumberHelper::convert($total) : $this->total;
    }

    public static function getCartByOrderId($id)
    {
        $cart = self::find()->joinWith(['order', 'order.location', 'order.costCenter'])
            ->where(['cart.order_id' => $id])->one();
        $temp = [];
        if ($cart) {
            $temp = [
                'id'               => $cart->id,
                'order_id'         => $cart->order_id,
                'order'            => ($cart->order) ? $cart->order : null,
                'user_id'          => $cart->user_id,
                'created_at'       => $cart->created_at,
                'updated_at'       => $cart->updated_at,
                'company_id'       => $cart->company_id,
                'location_id'      => ($cart->order) ? $cart->order->location_id : 0,
                'location_name'    => ($cart->order && $cart->order->location) ? $cart->order->location->name : '',
                'cost_center_id'   => ($cart->order) ? $cart->order->cost_center_id : 0,
                'cost_center_name' => ($cart->order && $cart->order->costCenter) ? $cart->order->costCenter->name : '',
                'total_sum'        => ($cart->order) ? $cart->order->total_sum : 0,
                'total'            => $cart->total
            ];
        }
        return $temp;
    }
}
