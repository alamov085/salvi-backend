<?php

namespace common\models;

use api\helpers\NotificationHelper;
use Yii;

/**
 * This is the model class for table "order_file".
 *
 * @property int $id
 * @property int $order_id
 * @property string $old_name
 * @property string $new_name
 * @property string $ext
 * @property int $size
 * @property int $user_id
 * @property string $filePath
 * @property int $created_at
 */
class OrderFile extends \yii\db\ActiveRecord
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'order_file';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['order_id', 'size', 'user_id', 'created_at'], 'integer'],
            [['old_name', 'new_name', 'ext'], 'string', 'max' => 255],
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'order_id' => 'Order ID',
            'old_name' => 'Old Name',
            'new_name' => 'New Name',
            'ext' => 'Ext',
            'size' => 'Size',
            'user_id' => 'User ID',
            'created_at' => 'Created At',
        ];
    }

    /**
     * @return string
     */
    public function getFilePath()
    {
        $path = Yii::getAlias('@files') . '/' . $this->order_id . '/' . $this->new_name . '.' . $this->ext;
        return $path;
    }

    public function beforeDelete()
    {
        /** @var  $user User */
        $user = Yii::$app->user->getIdentity();
        $order = Order::findOne(['id' => $this->order_id]);
        NotificationHelper::deleteFileFromOrder($order, $user, $this->old_name);
        NotificationHelper::deleteFileFromOrderOwner($order, $user, $this->old_name);
        return parent::beforeDelete(); // TODO: Change the autogenerated stub
    }
}
