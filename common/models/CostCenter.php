<?php

namespace common\models;

use api\helpers\NotificationHelper;
use Exception;
use Throwable;
use Yii;
use yii\db\ActiveQuery;
use yii\db\ActiveRecord;
use yii\db\StaleObjectException;

/**
 * This is the model class for table "cost_center".
 *
 * @property int $id
 * @property string $name
 * @property int $location_id
 * @property int $created_at
 * @property ActiveQuery|Locations $location
 * @property int $updated_at
 * @property string $uuid_client
 * @property History|ActiveQuery $history
 * @property string $uuid_contract
 */
class CostCenter extends ActiveRecord
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'cost_center';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['location_id', 'created_at', 'updated_at'], 'integer'],
            [['name', 'uuid_client', 'uuid_contract'], 'string', 'max' => 255],
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'name' => 'Name',
            'location_id' => 'Location ID',
            'created_at' => 'Created At',
            'updated_at' => 'Updated At',
        ];
    }

    /**
     * @return ActiveQuery | Locations
     */
    public function getLocation()
    {
        return $this->hasOne(Locations::class, ['id' => 'location_id']);
    }

    public function save($runValidation = true, $attributeNames = null)
    {
        if ($this->isNewRecord) {
            $this->created_at = date('U');
        }
        $this->updated_at = date('U');
        return parent::save($runValidation, $attributeNames); // TODO: Change the autogenerated stub
    }

    /**
     * @param $id
     * @param $data
     */
    public static function addCostCenters($id, $data)
    {
        //Убрал batchInsert чтобы записовать историю
        if (!empty($data)) {
            foreach ($data as $value) {
                $model = new CostCenter([
                    'location_id' => $id,
                    'name' => $value['name']
                ]);
                $model->save();
            }
        }
    }

    /**
     * @param $id
     * @param $data
     * @throws Throwable
     * @throws StaleObjectException
     */
    public static function updateCostCenters($id, $data)
    {
        $allIds = [];
        if (!empty($data)) {
            foreach ($data as $value) {
                if (isset($value['id'])) {
                    $model = self::find()->where(['id' => $value['id']])->one();
                } else {
                    $model = new self();
                }
                $model->location_id = $id;
                $model->name = $value['name'];
                if (!empty($value['name'])) {
                    $model->save();
                }
                if ($model->id) {
                    $allIds[] = $model->id;
                }
            }
        }
        $costs = self::find()
            ->where(['not in', 'id', $allIds])
            ->andWhere(['location_id' => $id])
            ->all();
        if ($costs != false) {
            NotificationHelper::deletedCostCenter($id, $costs);
            foreach ($costs as $cost) {
                $cost->delete();
            }
        }
    }

    /**
     * @return bool
     */
    public function beforeDelete()
    {
        UserCostCenter::deleteAll(['cost_center_id' => $this->id]);
        BudgetCostCenter::deleteAll(['cost_center_id' => $this->id]);
        return parent::beforeDelete(); // TODO: Change the autogenerated stub
    }

    public function afterSave($insert, $changedAttributes)
    {
        if ($insert) {
            History::saveHistory(History::COST_CENTER, $this->id);
        }
        parent::afterSave($insert, $changedAttributes);
    }

    /**
     * @return ActiveQuery | History
     */
    public function getHistory()
    {
        return $this->hasOne(History::class, ['entity_id' => 'id'])
            ->andOnCondition(['entity' => History::COST_CENTER]);
    }
}
