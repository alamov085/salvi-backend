<?php

namespace common\models;

use common\models\query\ContractAQ;
use Yii;
use yii\db\ActiveQuery;
use yii\db\ActiveRecord;
use yii\helpers\ArrayHelper;

/**
 * This is the model class for table "contract".
 *
 * @property int $id
 * @property int $company_id
 * @property string $name
 * @property string $number
 * @property int $supplier_id
 * @property int $company_entity_id
 * @property int $date_start
 * @property int $date_end
 * @property int $location_id
 * @property string $comment
 * @property int $status
 * @property int $created_at
 * @property ContractCostCenter|ActiveQuery $costCenters
 * @property ActiveQuery|CompanyEntity $companyEntity
 * @property Supplier|ActiveQuery $supplier
 * @property ActiveQuery|ContractLocation $locations
 * @property int $updated_at
 * @property array $listOfLocations
 * @property History|ActiveQuery $history
 * @property int $all_location
 * @property int $date_send_noty_end
 */
class Contract extends ActiveRecord
{
    const STATUS_ACTIVE = 1;
    const STATUS_NON_ACTIVE = 0;

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'contract';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['company_id', 'supplier_id', 'company_entity_id', 'date_start', 'date_end',
                'location_id', 'status', 'created_at', 'updated_at'], 'integer'],
            [['comment'], 'string'],
            [['name', 'number'], 'string', 'max' => 255],
            ['all_location', 'safe']
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'company_id' => 'Company ID',
            'name' => 'Name',
            'number' => 'Number',
            'supplier_id' => 'Supplier ID',
            'company_entity_id' => 'Company Entity ID',
            'date_start' => 'Date Start',
            'date_end' => 'Date End',
            'location_id' => 'Location ID',
            'comment' => 'Comment',
            'status' => 'Status',
            'created_at' => 'Created At',
            'updated_at' => 'Updated At',
        ];
    }

    public function save($runValidation = true, $attributeNames = null)
    {
        if ($this->isNewRecord) {
            $this->created_at = date('U');
        }
        $this->updated_at = date('U');
        return parent::save($runValidation, $attributeNames); // TODO: Change the autogenerated stub
    }

    /**
     * @return ActiveQuery | ContractCostCenter
     */
    public function getCostCenters()
    {
        return $this->hasMany(ContractCostCenter::class, ['contract_id' => 'id']);
    }

    /**
     * @return ActiveQuery | Supplier
     */
    public function getSupplier()
    {
        return $this->hasOne(Supplier::class, ['id' => 'supplier_id']);
    }

    /**
     * @return ActiveQuery | CompanyEntity
     */
    public function getCompanyEntity()
    {
        return $this->hasOne(CompanyEntity::class, ['id' => 'company_entity_id']);
    }

    /**
     * @return ActiveQuery | ContractLocation
     */
    public function getLocations()
    {
        return $this->hasMany(ContractLocation::class, ['contract_id' => 'id']);
    }

    /**
     * @return array
     */
    public function getListOfLocations()
    {
        if ($this->all_location) {
            $locations = Locations::find()
                ->where(['company_id' => $this->company_id])
                ->asArray()
                ->all();
            if ($locations) {
                return ArrayHelper::getColumn($locations, 'id');
            }
        } else {
            $locations = $this->locations;
            return ArrayHelper::getColumn($locations, 'location_id');
        }
        return [];
    }

    public static function find()
    {
        return new ContractAQ(get_called_class());
    }

    public function afterSave($insert, $changedAttributes)
    {
        if ($insert) {
            History::saveHistory(History::CONTRACT, $this->id);
        }
        parent::afterSave($insert, $changedAttributes);
    }

    /**
     * @return ActiveQuery | History
     */
    public function getHistory()
    {
        return $this->hasOne(History::class, ['entity_id' => 'id'])
            ->andOnCondition(['entity' => History::CONTRACT]);
    }
}
