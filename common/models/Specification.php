<?php

namespace common\models;

use common\models\query\SpecificationAQ;
use Exception;
use Yii;
use yii\db\ActiveQuery;
use yii\db\ActiveRecord;
use yii\helpers\ArrayHelper;
use yii\caching\TagDependency;


/**
 * This is the model class for table "specification".
 *
 * @property int $id
 * @property int $company_id
 * @property string $name
 * @property int $contract_id
 * @property int $date_start
 * @property int $date_end
 * @property int $status
 * @property int $created_at
 * @property ActiveQuery|SpecificationProduct $products
 * @property ActiveQuery|SpecificationLocation $locations
 * @property ActiveQuery|Contract $contract
 * @property ActiveQuery|Company $company
 * @property ActiveQuery|Locations $locationsModel
 * @property History|ActiveQuery $history
 * @property int $updated_at
 * @property int $markup
 * @property int $all_location
 */
class Specification extends ActiveRecord
{
    const STATUS_NON_ACTIVE = 0;
    const STATUS_ACTIVE = 1;

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'specification';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['company_id', 'contract_id', 'date_start', 'date_end', 'status', 'created_at', 'updated_at',
                'all_location'], 'integer'],
            [['name'], 'string', 'max' => 255],
            ['markup', 'safe']
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'company_id' => 'Company ID',
            'name' => 'Name',
            'contract_id' => 'Contract ID',
            'date_start' => 'Date Start',
            'date_end' => 'Date End',
            'status' => 'Status',
            'created_at' => 'Created At',
            'updated_at' => 'Updated At',
        ];
    }

    /**
     * @return ActiveQuery | SpecificationLocation
     */
    public function getLocations()
    {
        return $this->hasMany(SpecificationLocation::class, ['specification_id' => 'id']);
    }

    /**
     * @return ActiveQuery | SpecificationProduct
     */
    public function getProducts()
    {
        return $this->hasMany(SpecificationProduct::class, ['specification_id' => 'id']);
    }

    public function save($runValidation = true, $attributeNames = null)
    {
        if ($this->isNewRecord) {
            $this->created_at = date('U');
        }
        $this->updated_at = date('U');
        return parent::save($runValidation, $attributeNames); // TODO: Change the autogenerated stub
    }

    /**
     * @return ActiveQuery | Contract
     */
    public function getContract()
    {
        return $this->hasOne(Contract::class, ['id' => 'contract_id']);
    }

    /**
     * @param $products
     * @return bool
     */
    public function addProducts($products)
    {
        if (!empty($products)) {
            $productsIndex = ArrayHelper::index($products, 'uuid');
            $productsUuid = ArrayHelper::getColumn($products, 'uuid');
            $specificationProducts = SpecificationProduct::find()
                ->where(['specification_id' => $this->id])
                ->andWhere(['in', 'product_uuid', $productsUuid])
                ->all();
            $specificationProductsUuid = [];
            if ($specificationProducts) {
                $specificationProductsUuid = ArrayHelper::getColumn($specificationProducts, 'product_uuid');
            }
            $totalList = array_diff($productsUuid, $specificationProductsUuid);
            $result = [];
            if ($totalList) {
                $productItems = Product::find()
                    ->where(['in', 'uuid', $totalList])
                    ->all();
                $productItem = ArrayHelper::index($productItems, 'uuid');
                foreach ($totalList as $index) {
                    $use_markup = 0;
                    $markup = 0;
                    $price = ArrayHelper::getValue($productItem, $index . '.buy_price', 0);
                    if (isset($productsIndex[$index]['markup'])) {
                        $use_markup = 1;
                        $markup = $productsIndex[$index]['markup'];
                        $price *= ($markup + 100) / 100;
                    }
                    $result[] = [
                        'product_id' => ArrayHelper::getValue($productsIndex, $index . '.id'),
                        'product_uuid' => $index,
                        'specification_id' => $this->id,
                        'price' => $price,
                        'markup' => $markup,
                        'manual_markup' => 0,
                        'use_markup' => $use_markup
                    ];
                }
                if (!empty($result)) {
                    try {
                        Yii::$app->db->createCommand()->batchInsert(
                            SpecificationProduct::tableName(),
                            [
                                'product_id',
                                'product_uuid',
                                'specification_id',
                                'price',
                                'markup',
                                'manual_markup',
                                'use_markup'
                            ],
                            $result
                        )->execute();
                    } catch (Exception $e) {
                        Yii::error($e);
                        return false;
                    }
                    return true;
                }
            }
        }
        return false;
    }

    /**
     * @return ActiveQuery | Company
     */
    public function getCompany()
    {
        return $this->hasOne(Company::class, ['id' => 'company_id']);
    }

    /**
     * @return ActiveQuery | Locations
     */
    public function getLocationsModel()
    {
        return $this->hasMany(Locations::class, ['id' => 'location_id'])
            ->via('locations');
    }

    /**
     * @return SpecificationAQ|ActiveQuery
     */
    public static function find()
    {
        return new SpecificationAQ(get_called_class());
    }

    public function afterDelete()
    {
        SpecificationLocation::deleteAll(['specification_id' => $this->id]);
        SpecificationProduct::deleteAll(['specification_id' => $this->id]);
        parent::afterDelete();
    }

    public function afterSave($insert, $changedAttributes)
    {
        if ($insert) {
            History::saveHistory(History::SPECIFICATION, $this->id);
        }
        parent::afterSave($insert, $changedAttributes);
    }

    /**
     * @return ActiveQuery | History
     */
    public function getHistory()
    {
        return $this->hasOne(History::class, ['entity_id' => 'id'])
            ->andOnCondition(['entity' => History::SPECIFICATION]);
    }

    public static function specificationsInPeriod(Specification $specification)
    {
        $specifications = Specification::find()
            ->select(['id'])
            ->where(['status' => Specification::STATUS_ACTIVE])
            ->andWhere([
                'or',
                [
                    'and',
                    ['<=', 'date_start', $specification->date_start],
                    ['>=', 'date_end', $specification->date_start]
                ],
                [
                    'and',
                    ['<=', 'date_start', $specification->date_end],
                    ['>=', 'date_end', $specification->date_end]
                ],
                [
                    'and',
                    ['>=', 'date_start', $specification->date_start],
                    ['<=', 'date_end', $specification->date_end]
                ],
                [
                    'and',
                    ['>=', 'date_start', $specification->date_start],
                    ['>=', 'date_end', $specification->date_end],
                    ['<=', 'date_start', $specification->date_end]
                ]
            ])
            ->andWhere(['company_id' => $specification->company_id])
            ->andWhere(['!=', 'id', $specification->id])
            ->asArray()
            ->all();
        return ArrayHelper::getColumn($specifications, 'id');
    }

    /**
     * @param array $locations
     * @param bool $all_location
     * @return array|Specification[]|ActiveRecord[]
     * @throws \Throwable
     */
    public static function getListByLocation(array $locations, bool $all_location)
    {
        /** @var  $user User */
        $user = Yii::$app->user->getIdentity();
        if ($all_location) {
            $locationList = Locations::find()
                ->where(['company_id' => $user->company_id])
                ->asArray()
                ->all();
            if ($locationList) {
                $locations = ArrayHelper::getColumn($locationList, 'id');
            } else {
                $locations = [];
            }
        }
        $data = [];
        if ($locations) {
            $specLocation = SpecificationLocation::find()
                ->select(['specification_id'])
                ->where(['in', 'location_id', $locations])
                ->groupBy(['specification_id'])
                ->asArray()
                ->all();
            $data = Specification::find()
                ->where(['company_id' => $user->company_id])
                ->andWhere(['in', 'id', ArrayHelper::getColumn($specLocation, 'specification_id')])
                ->all();
        }
        return $data;
    }

    public static function getListByParams($locationId,$userCompanyId,$orderId = 0)
    {
        $specificationsQuery = Specification::find()
            ->innerJoin(
                'specification_location',
                'specification_location.specification_id = specification.id'
            )
            ->where([
                'specification.company_id' => $userCompanyId
            ])
            ->active();

        if (!empty($orderId) && $orderId > 0)
        {
            $order = Order::findOne($orderId);

            if ($order)
            {
                $budgetSpecificationIds = BudgetSpecification::find()
                    ->select('specification_id')
                    ->where([
                        'budget_id' => $order->budget_id
                    ])
                    ->column();

                if ($budgetSpecificationIds)
                {
                    $specificationsQuery->andWhere([
                        'specification.id' => $budgetSpecificationIds
                    ]);
                }

                if (!$locationId)
                {
                    $locationId = $order->location_id;
                }
            }
        }

        if ($locationId)
        {
            $specificationsQuery->andWhere([
                'specification_location.location_id' => $locationId
            ]);
        }

        $hashSql = md5($specificationsQuery->createCommand()->getRawSql());

        $result = Yii::$app->cache->get('getListByParamsSpecification_' . $hashSql);

        if (!$result)
        {
            $result = $specificationsQuery->all();

            Yii::$app->cache->set('getListByParamsSpecification_' . $hashSql, $result, 260000,new TagDependency(['tags'=>['getListByParamsSpecification']]));
        }

        return $result;
    }
}
