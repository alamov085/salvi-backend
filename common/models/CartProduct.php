<?php

namespace common\models;

use Exception;
use Yii;
use yii\db\ActiveQuery;
use yii\db\ActiveRecord;
use yii\helpers\ArrayHelper;

/**
 * This is the model class for table "cart_product".
 *
 * @property int $id
 * @property int $cart_id
 * @property int $product_id
 * @property string $product_uuid
 * @property int $quantity
 * @property int $new_quantity
 * @property string $price
 * @property string $total_sum
 * @property Product|ActiveQuery $product
 * @property int $status
 * @property boolean $last_update
 * @property boolean $is_delete
 */
class CartProduct extends ActiveRecord
{
    const STATUS_AT_ORDER = 0;
    const STATUS_NEW = 1;
    const STATUS_CHANGE_QUANTITY = 2;

    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'cart_product';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['cart_id', 'product_id', 'quantity', 'new_quantity', 'status'], 'integer'],
            [['price', 'total_sum'], 'number'],
            [['product_uuid'], 'string', 'max' => 255],
            [['last_update', 'is_delete'], 'boolean']
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id'           => 'ID',
            'cart_id'      => 'Cart ID',
            'product_id'   => 'Product ID',
            'product_uuid' => 'Product Uuid',
            'quantity'     => 'Quantity',
            'new_quantity' => 'New Quantity',
            'price'        => 'Price',
            'total_sum'    => 'Total Sum',
            'status'       => 'Status',
        ];
    }

    /**
     * @return ActiveQuery | Product
     */
    public function getProduct()
    {
        return $this->hasOne(Product::class, ['uuid' => 'product_uuid']);
    }

    public function save($runValidation = true, $attributeNames = null)
    {
        /** @var  $user User */
        try {
            $user = Yii::$app->user->getIdentity();
        } catch (\Exception $e) {
            $user = User::findOne(['id' => 1]);

        }
        $this->last_update = true;
        if ($this->isNewRecord) {
            $model = new CartProductHistory([
                'cart_id'  => $this->cart_id,
                'user_id'  => $user->id,
                'username' => $user->email,
                'message'  => 'Доданий товар ' . ArrayHelper::getValue($this->product, 'name', '') . ' в кількості ' . $this->quantity . ' ' .
                    ArrayHelper::getValue($this->product, 'unit.name', 'шт.')]);
            $model->save();
        }
        $result = parent::save($runValidation, $attributeNames);
        CartProduct::updateAll(
            ['last_update' => false],
            [
                'and',
                ['cart_id' => $this->cart_id],
                ['!=', 'id', $this->id]
            ]
        );
        return $result;
    }

    public function addHistory($message)
    {
        /** @var  $user User */
        $user = Yii::$app->user->getIdentity();
        $model = new CartProductHistory([
            'cart_id'  => $this->cart_id,
            'user_id'  => $user->id,
            'username' => $user->email,
            'message'  => $message
        ]);
        return $model->save();
    }

    public function beforeDelete()
    {
        /** @var  $user User */
        $user = Yii::$app->user->getIdentity();
        $model = new CartProductHistory([
            'cart_id'  => $this->cart_id,
            'user_id'  => $user->id,
            'username' => $user->email,
            'message'  => 'Видалений товар ' . $this->product->name
        ]);
        $model->save();
        return parent::beforeDelete(); // TODO: Change the autogenerated stub
    }

    public function saveWithSocket($order_id = 0)
    {
        $result = $this->save();
        if ($result) {
            /** @var  $user User */
            $user = Yii::$app->user->getIdentity();
            try {
                $redis = Yii::$app->redis;
                $redis->publish(
                    'userCartAction',
                    [
                        'order_id' => $order_id,
                        'user_id'  => $user->id,
                        'update'   => true
                    ]
                );
                $redis->close();
            } catch (Exception $e) {
                Yii::error($e->getMessage());
            }
        }
        return $result;
    }
}
