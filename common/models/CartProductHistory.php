<?php

namespace common\models;

use Yii;

/**
 * This is the model class for table "cart_product_history".
 *
 * @property int $id
 * @property int $cart_id
 * @property int $user_id
 * @property string $username
 * @property string $message
 * @property int $created_at
 */
class CartProductHistory extends \yii\db\ActiveRecord
{
    /**
     * {@inheritdoc}
     */
    public static function tableName()
    {
        return 'cart_product_history';
    }

    /**
     * {@inheritdoc}
     */
    public function rules()
    {
        return [
            [['cart_id', 'user_id', 'created_at'], 'integer'],
            [['username', 'message'], 'string', 'max' => 255],
        ];
    }

    /**
     * {@inheritdoc}
     */
    public function attributeLabels()
    {
        return [
            'id' => 'ID',
            'cart_id' => 'Cart ID',
            'user_id' => 'User ID',
            'username' => 'Username',
            'message' => 'Message',
            'created_at' => 'Created At',
        ];
    }

    public function save($runValidation = true, $attributeNames = null)
    {
        $cache = Yii::$app->cache->get('CartProductHistory_' . $this->cart_id);

        if($cache)
        {
            Yii::$app->cache->delete('CartProductHistory_' . $this->cart_id);
        }

        $this->created_at = date('U');
        return parent::save($runValidation, $attributeNames); // TODO: Change the autogenerated stub
    }
}
