namespace api\models\forms;

use common\helpers\UserSecurity;
use common\models\User;
use common\models\UserCostCenter;
use common\models\UserLocation;
use Throwable;
use Yii;
use yii\base\Exception;
use yii\base\Model;

/**
 * Class UserForm
 * @package api\models\forms
 */
class UserForm extends Model
{
    public $first_name;
    public $last_name;
    public $phone_number;
    public $password;
    public $repeatPassword;
    public $position;
    public $currency_id;
    public $location_id;
    public $cost_center = [];
    public $locations = [];
    public $email;
    public $username;
    public $is_sending_mail;

    public $_passwordDifficult;

    /**
     * @return array
     */
    public function rules()
    {
        return [
            [['first_name', 'last_name', 'phone_number'], 'required'],
            ['phone_number', 'match', 'pattern' => '/^\d{9}$/', 'message' => 'Поле має містити 9 цифр'],
            [['first_name', 'last_name'], 'string'],
            [['position', 'location_id', 'repeatPassword', 'password'], 'safe'],
            [['phone_number', 'currency_id','is_sending_mail'], 'integer'],
            [['currency_id', 'locations', 'cost_center'], 'safe'],
            ['phone_number', 'validateUniq'],
            ['email', 'validateUniqEmail'],
            ['username', 'validateUniqEmail'],
        ];
    }

    /**
     * @throws Throwable
     * @throws Exception
     */
    public function save()
    {
        /** @var  $model User */
        $model = Yii::$app->user->getIdentity();
        $model->first_name = $this->first_name;
        $model->last_name = $this->last_name;
        $model->phone_number = $this->phone_number;
        $model->position = $this->position;
        $model->currency_id = $this->currency_id;
        $model->email = $this->email;
        $model->username = $this->email;
        $model->is_sending_mail = $this->is_sending_mail;
        if (!is_null($this->password)) {
            $model->password_difficult = $this->_passwordDifficult;
            $model->setPassword($this->password);
        }
        $result = $model->save();
        if (Yii::$app->user->can('updateProfileAddFields')) {
            UserCostCenter::deleteAll(['user_id' => $model->id]);
            if (!empty($this->cost_center)) {
                foreach ($this->cost_center as $cost) {
                    $costModel = new UserCostCenter();
                    $costModel->user_id = $model->id;
                    $costModel->cost_center_id = (int)$cost;
                    $costModel->save();
                }
            }
            UserLocation::deleteAll(['user_id' => $model->id]);
            if (!empty($this->locations)) {
                foreach ($this->locations as $location) {
                    $locationModel = new UserLocation();
                    $locationModel->user_id = $model->id;
                    $locationModel->location_id = (int)$location;
                    $locationModel->save();
                }
            }
        }
        return $result;
    }

    /**
     * @return bool
     */
    public function passwordValidate()
    {
        $this->_passwordDifficult = UserSecurity::getPassLevel($this->password);
        if ($this->_passwordDifficult) {
            return true;
        } else {
            $this->addError(
                'repeatPassword',
                'Пароль повинен містити як мінімум 8 символів, 1 велику літеру і 1 цифру'
            );
            return false;
        }
    }

    public function validate($attributeNames = null, $clearErrors = true)
    {
        if (!is_null($this->password) && !is_null($this->repeatPassword) && !empty($this->repeatPassword)) {
            if ($this->password != $this->repeatPassword) {
                $this->addError('password', 'Паролі повинні бути однакові');
                return false;
            }
            return $this->passwordValidate();
        }
        return parent::validate($attributeNames, $clearErrors); // TODO: Change the autogenerated stub
    }

    /**
     * @return array
     */
    public function attributeLabels()
    {
        return [
            'first_name' => 'Ім\'я',
            'last_name' => 'Прізвище',
            'phone_number' => 'Мобільний телефон',
            'position' => 'Посада',
            'currency_id' => 'Валюта',
            'location_id' => 'Головна локація',
            'password' => 'Пароль',
            'repeatPassword' => 'Повторіть пароль'
        ];
    }

    public function validateUniq()
    {
        $company = User::find()
            ->where(['!=', 'id',  Yii::$app->user->getId()])
            ->andWhere(['phone_number' => $this->phone_number])
            ->exists();
        if ($company) {
            $this->addError('phone_number', 'Цей телефон вже зайнятий');
        }
    }

    public function validateUniqEmail() {
        $user = User::find()
            ->where(['!=', 'id', Yii::$app->user->getId()])
            ->andWhere(['email' => $this->email])
            ->exists();

        if($user) {
            $this->addError('email', 'Цей e-mail вже зайнятий іншим користувачем');
        }
    }

    public function randomPassword($length) {
        //A list of characters that can be used in our
        //random password.
        $characters = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ';
        //Create a blank string.
        $password = '';
        //Get the index of the last character in our $characters string.
        $characterListLength = mb_strlen($characters, '8bit') - 1;
        //Loop from 1 to the $length that was specified.
        foreach(range(1, $length) as $i){
            $password .= $characters[random_int(0, $characterListLength)];
        }

        if(!preg_match('#[A-Za-z\d+]#', $password)) {
            $password = $this->randomPassword($length);
        }

        return $password;
    }
}
