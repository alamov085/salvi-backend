    /**
     * @return bool
     * @throws \Throwable
     */
    public function update()
    {
        /** @var  $user User */
        $user = Yii::$app->user->getIdentity();
        
      
        $model = Order::find()
            ->where(['id' => $this->id])
            ->andWhere(['company_id' => $user->company_id])
            ->one();
        
        if ($model) {
            $model->company_entity_id = $this->company_entity_id;
            $model->location_id = $this->location_id;
            $model->cost_center_id = $this->cost_center_id;
            $model->contract_id = $this->contract_id;
            $model->budget_id = $this->budget_id;
            $model->comment = $this->comment;
            $model->delivery_date = (!empty($this->delivery_date) && $this->delivery_date != 'null') ? strtotime($this->delivery_date) : null;
            $model->ro_number = $this->ro_number;
            $model->one_day_shipment  = $this->one_day_shipment;
            
            $result = $model->save();
        
            if ($result) {
                OrderHelper::calculateProductsUpdate($model);
                $model->total_sum = OrderHelper::getTotalSum($this->id);
                $model->save();
                return $model->id;
            }
        }
        return false;
    }
    
    public function getListNoAvailableProductForDuplicateOrder()
    {
        $noAvailableProduct = [];

        $noAvailableProduct['products'] = [];

        $noAvailableProduct['isAll'] = false;

        $oldOrder = Order::find()->where(['id' => $this->copy_id])->one();

        if ($oldOrder)
        {
            $products = OrderProduct::find()->where(['order_id' => $this->copy_id])->all();

            if ($products)
            {
                $products = OrderHelper::prepareProductAttrForCheckDuplicateOrder($products,$this);

                $productList = [];

                $productListTmp = Product::find()
                    ->where(['id' => array_column($products,'product_id')])
                    ->select(['id','name','sku','deleted'])
                    ->all();

                foreach ($productListTmp as $item)
                {
                    $productList[$item->id] = $item;
                }

                foreach ($products as $product)
                {
                    if(!isset($productList[$product->product_id]))
                    {
                        $noAvailableProduct['products'][] = [
                            'id' => 0,
                            'name' => $product->name,
                            'sku' => '',
                            'deleted' => 0,
                            'photo' => '',
                        ];

                        continue;
                    }

                    if($productList[$product->product_id]->deleted > 0 || $product->view_only == 1)
                    {
                        $photoPath = '';

                        $photo = ProductPhoto::find()
                            ->where(['product_id' => $product->product_id])
                            ->select(['name','product_id'])
                            ->all();

                        if(!empty($photo))
                        {
                            $photoPath = Yii::$app->urlManager->createAbsoluteUrl(['/product/' . $photo[0]->name]);
                        }

                        $noAvailableProduct['products'][] = [
                            'id' => $productList[$product->product_id]->id,
                            'name' => $productList[$product->product_id]->name,
                            'sku' => $productList[$product->product_id]->sku,
                            'deleted' => $productList[$product->product_id]->deleted,
                            'photo' => $photoPath,
                        ];
                    }
                }

                if(count($products) == count($noAvailableProduct['products']))
                {
                    $noAvailableProduct['isAll'] = true;
                }
            }
        }

        return $noAvailableProduct;
    }

    public function duplicate()
    {
        $oldOrder = Order::find()->where(['id' => $this->copy_id])->one();
        if ($oldOrder) {
            /** @var  $user User */
            $user = Yii::$app->user->getIdentity();
            $company = Company::find()->where(['id' => $user->company_id])->one();
            $model = new Order();
            $model->setAttributes([
                'company_entity_id' => $this->company_entity_id,
                'location_id'       => $this->location_id,
                'cost_center_id'    => $this->cost_center_id,
                'contract_id'       => $this->contract_id,
                'budget_id'         => $this->budget_id,
                'comment'           => $this->comment,
                'delivery_date'     => $this->delivery_date,
                'company_id'        => $user->company_id,
                'created_by_user'   => $user->id,
                'total_sum'         => 0,
                'status'            => 0,
                'non_budget_order'  => $company->non_budget_order,
                'coordination'      => $company->coordination,
                'empty_string'      => ArrayHelper::getValue($company, 'empty_string', 0)
            ]);
            $result = $model->save();
            if ($result) {
                $cart = new Cart([
                    'user_id'    => 0,
                    'total'      => 0,
                    'company_id' => $model->company_id,
                    'order_id'   => $model->id
                ]);
                $cart->save();
                //\Yii::error($cart);
                $products = OrderProduct::find()->where(['order_id' => $this->copy_id])->all();

                if ($products)
                {
                    $products = OrderHelper::prepareProductAttrForCheckDuplicateOrder($products,$this);

                    $productList = [];

                    $productListTmp = Product::find()->where(['id' => array_column($products,'product_id')])->select(['id','deleted'])->all();

                    foreach ($productListTmp as $item)
                    {
                        $productList[$item->id] = $item;
                    }

                    foreach ($products as $product)
                    {
                        if(!isset($productList[$product->product_id]))
                        {
                            continue;
                        }

                        if($productList[$product->product_id]->deleted > 0 || $product->view_only == 1)
                        {
                            continue;
                        }

                        $newProduct = new OrderProduct();
                        $newProduct->setAttributes($product->attributes);
                        $newProduct->order_id = $model->id;
                        $newProduct->approved = 0;
                        $newProduct->catalog = $product->getCatalogValue();
                        $newProduct->save();
                    }
                }
                OrderHelper::calculateProductsUpdate($model);
                if ($cart) {
                    $cartForm = new CartForm(['id' => $cart->id, 'order_id' => $cart->order_id]);
                    $cartForm->clearCart();
                }
                $oldOrder->copyCoordination($model);
                $oldOrder->copyUserCoordination($model);
                $model->total_sum = OrderHelper::getTotalSum($model->id);
                $model->save();
            }
            return ($result) ? $model->id : $result;
        }
        return false;
    }
