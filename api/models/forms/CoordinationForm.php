namespace api\models\forms;

use api\helpers\NotificationHelper;
use common\models\AuthAssignment;
use common\models\Coordination;
use common\models\CoordinationRoles;
use common\models\CoordinationUsers;
use common\models\User;
use Throwable;
use Yii;
use yii\base\Model;
use yii\helpers\ArrayHelper;

/**
 * Class CoordinationForm
 * @package api\models\forms
 */
class CoordinationForm extends Model
{
    public $id;
    public $name;
    public $sum;
    public $type;
    public $status;
    public $order;
    public $all_roles;
    public $roles;
    public $users;
    public $additional_type;
    public $enable_notification;

    /**
     * @return array
     */
    public function rules()
    {
        return [
            [['name'], 'required'],
            [['id', 'type', 'status', 'order', 'additional_type'], 'integer'],
            [['all_roles', 'enable_notification'], 'boolean'],
            [['sum'], 'number'],
            [['name'], 'string', 'max' => 255],
            [['roles', 'users'], 'safe']
        ];
    }

    public function validate($attributeNames = null, $clearErrors = true)
    {
        if (empty($this->roles)) {
            return $this->addError('roles', 'Виберіть хоча б одну роль');
        }
        if (empty($this->users) && !$this->all_roles) {
            return $this->addError('all_roles', 'Виберіть хоча б одного користувача');
        }
        if (!empty($this->users) && !$this->all_roles) {
            $users = User::find()
                ->where(['in', 'id', $this->users])
                ->andWhere(['status' => User::STATUS_ACTIVE])
                ->exists();
            if (!$users) {
                return $this->addError('users', 'Виберіть хоча б одного активного користувача');
            }
        }
        return parent::validate($attributeNames, $clearErrors); // TODO: Change the autogenerated stub
    }

    /**
     * @return bool
     * @throws Throwable
     */
    public function create()
    {
        /** @var  $user User */
        $user = Yii::$app->user->getIdentity();
        $order = Coordination::find()->where(['company_id' => $user->company_id])->count();
        $model = new Coordination();
        $model->name = $this->name;
        $model->sum = $this->sum;
        $model->type = $this->type;
        $model->all_roles = $this->all_roles;
        $model->company_id = $user->company_id;
        $model->additional_type = $this->additional_type;
        $model->order = $order + 1;
        $model->status = 1;
        $model->enable_notification = $this->enable_notification;
        $result = $model->save();
        if ($result) {
            CoordinationUsers::addUsers($model->id, $this->users);
            CoordinationRoles::addRoles($model->id, $this->roles);
            if (empty($this->users)) {
                $users = AuthAssignment::find()
                    ->where(['in', 'item_name', $this->roles])
                    ->all();
                if ($users) {
                    $activeUsers = User::find()->where(['status' => User::STATUS_ACTIVE])
                        ->andWhere(['in', 'id', ArrayHelper::getColumn($users, 'user_id')])
                        ->andWhere(['manager' => 0])
                        ->andWhere(['company_id' => $user->company_id])
                        ->all();
                    if ($activeUsers) {
                        $users = ArrayHelper::getColumn($activeUsers, 'id');
                    }
                } else {
                    $users = [];
                }
            } else {
                $users = $this->users;
            }
            NotificationHelper::youAreAtCoordination($users);
        }
        return $result;
    }

    /**
     * @return bool
     */
    public function update()
    {
        /** @var  $user User */
        $user = Yii::$app->user->getIdentity();
        $model = Coordination::find()->where(['id' => $this->id])->one();
        if ($model != false) {
            $model->name = $this->name;
            $model->sum = $this->sum;
            $model->type = $this->type;
            $model->additional_type = $this->additional_type;
            $model->all_roles = $this->all_roles;
            $model->enable_notification = $this->enable_notification;
            $result = $model->save();
            if ($result) {
                CoordinationRoles::deleteAll(['coordination_id' => $model->id]);
                CoordinationUsers::deleteAll(['coordination_id' => $model->id]);
                CoordinationUsers::addUsers($model->id, $this->users);
                CoordinationRoles::addRoles($model->id, $this->roles);
                if (empty($this->users)) {
                    $users = AuthAssignment::find()
                        ->where(['in', 'item_name', $this->roles])
                        ->all();
                    if ($users) {
                        $activeUsers = User::find()->where(['status' => User::STATUS_ACTIVE])
                            ->andWhere(['in', 'id', ArrayHelper::getColumn($users, 'user_id')])
                            ->andWhere(['manager' => 0])
                            ->andWhere(['company_id' => $user->company_id])
                            ->all();
                        if ($activeUsers) {
                            $users = ArrayHelper::getColumn($activeUsers, 'id');
                        }
                    } else {
                        $users = [];
                    }
                } else {
                    $users = $this->users;
                }
                NotificationHelper::youAreAtCoordination($users);
            }
            return $result;
        }
    }
}
